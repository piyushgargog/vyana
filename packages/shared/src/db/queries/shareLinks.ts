import type { DbShareLink } from "../types";
import { check, requireUserId, unwrap, type Sb } from "./helpers";

export type ShareKind = "medical_id" | "timeline";

export type CreatedShareLink = { token: string; url: string; expires_at: string };

/** Removes trailing slashes without a regular expression. */
export function trimTrailingSlashes(value: string): string {
  let end = value.length;
  while (end > 0 && value[end - 1] === "/") end--;
  return value.slice(0, end);
}

/** The public page of a share link: `{baseUrl}/share/{token}`. */
export function shareUrl(baseUrl: string, token: string): string {
  return `${trimTrailingSlashes(baseUrl)}/share/${token}`;
}

/**
 * Creates a read-only link that expires after `ttlHours`. The token is generated by the database;
 * `baseUrl` is the web app's address (APP_URL on the server, the API base URL on the clients).
 */
export async function createShareLink(sb: Sb, kind: ShareKind, ttlHours: number, baseUrl: string): Promise<CreatedShareLink> {
  const patientId = await requireUserId(sb);
  const expiresAt = new Date(Date.now() + ttlHours * 60 * 60 * 1000).toISOString();
  const row = unwrap(
    await sb.from("share_links").insert({ patient_id: patientId, kind, expires_at: expiresAt }).select("token, expires_at").single()
  );
  return { token: row.token, url: shareUrl(baseUrl, row.token), expires_at: row.expires_at };
}

/** The signed-in patient's links, newest first (revoked ones included, with `revoked: true`). */
export async function listShareLinks(sb: Sb): Promise<DbShareLink[]> {
  const patientId = await requireUserId(sb);
  return unwrap(await sb.from("share_links").select("*").eq("patient_id", patientId).order("created_at", { ascending: false }));
}

/** Turns a link off at once. The page then answers 404. */
export async function revokeShareLink(sb: Sb, token: string): Promise<void> {
  check(await sb.from("share_links").update({ revoked: true }).eq("token", token));
}
