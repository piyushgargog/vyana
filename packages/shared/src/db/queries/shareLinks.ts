import { SHARE_LINK_MAX_TTL_HOURS } from "../../constants";
import type { ShareScope } from "../../contracts";
import { isShareScope } from "../../health/memory";
import type { DbShareLink } from "../types";
import { check, DbError, requireUserId, unwrap, type Sb } from "./helpers";

export type ShareKind = "medical_id" | "timeline";

export type CreatedShareLink = { token: string; url: string; expires_at: string };

/** Removes trailing slashes without a regular expression. */
export function trimTrailingSlashes(value: string): string {
  let end = value.length;
  while (end > 0 && value[end - 1] === "/") end--;
  return value.slice(0, end);
}

/** The public page of a share link: `{baseUrl}/share/{token}`. */
export function shareUrl(baseUrl: string, token: string): string {
  return `${trimTrailingSlashes(baseUrl)}/share/${token}`;
}

/**
 * Creates a read-only link that expires after `ttlHours` (more than 0, at most `SHARE_LINK_MAX_TTL_HOURS`, 30 days).
 * The token is generated by the database; `baseUrl` is the web app's address (APP_URL on the server, the API base
 * URL on the clients). `scopes` (issue #237) names the parts of the record the link's page may show — the Health
 * Memory Graph; a link without scopes behaves exactly as links always have.
 */
export async function createShareLink(sb: Sb, kind: ShareKind, ttlHours: number, baseUrl: string, scopes: ShareScope[] = []): Promise<CreatedShareLink> {
  if (!Number.isFinite(ttlHours) || ttlHours <= 0 || ttlHours > SHARE_LINK_MAX_TTL_HOURS) {
    throw new DbError(`A share link must last more than 0 and at most ${SHARE_LINK_MAX_TTL_HOURS} hours`, "invalid_ttl");
  }
  if (!scopes.every(isShareScope)) {
    throw new DbError("A share link scope must be one of labs, vitals, medicines, adherence", "invalid_scopes");
  }
  const patientId = await requireUserId(sb);
  const expiresAt = new Date(Date.now() + ttlHours * 60 * 60 * 1000).toISOString();
  const row = unwrap(
    await sb.from("share_links").insert({ patient_id: patientId, kind, expires_at: expiresAt, scopes }).select("token, expires_at").single()
  );
  return { token: row.token, url: shareUrl(baseUrl, row.token), expires_at: row.expires_at };
}

/** The signed-in patient's links, newest first (revoked ones included, with `revoked: true`). */
export async function listShareLinks(sb: Sb): Promise<DbShareLink[]> {
  const patientId = await requireUserId(sb);
  return unwrap(await sb.from("share_links").select("*").eq("patient_id", patientId).order("created_at", { ascending: false }));
}

/** True while a link still opens its page: not turned off and not past its time. */
export function isShareLinkActive(link: Pick<DbShareLink, "revoked" | "expires_at">, now: Date = new Date()): boolean {
  return !link.revoked && new Date(link.expires_at).getTime() > now.getTime();
}

/** The token at the end of a share URL (`{baseUrl}/share/{token}`), or null. */
export function shareTokenFromUrl(url: string): string | null {
  let path: string;
  try {
    path = new URL(url).pathname;
  } catch {
    return null;
  }
  const parts = path.split("/").filter((part) => part !== "");
  const token = parts.length >= 2 && parts[parts.length - 2] === "share" ? parts[parts.length - 1] : "";
  return token !== "" && token.length <= 128 && [...token].every((c) => "0123456789abcdef".includes(c)) ? token : null;
}

/** True when `url` is a link of this patient that is turned off or expired (a link not in the list counts as live: the list may still be loading). */
export function isShareUrlDead(links: Pick<DbShareLink, "token" | "revoked" | "expires_at">[], url: string, now: Date = new Date()): boolean {
  const token = shareTokenFromUrl(url);
  const link = token ? links.find((l) => l.token === token) : undefined;
  return link ? !isShareLinkActive(link, now) : false;
}

/**
 * Turns a link off at once. The page then answers 404. A link that is not the patient's (or does not exist) changes
 * no row, and that is an error: the database would otherwise answer "ok" and the app would say it was turned off.
 */
export async function revokeShareLink(sb: Sb, token: string): Promise<void> {
  const rows = unwrap(await sb.from("share_links").update({ revoked: true }).eq("token", token).select("token"));
  if (rows.length === 0) throw new DbError("That link was not found", "not_found");
}
